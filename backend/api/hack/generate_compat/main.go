// Command generate_compat generates legacy Go import shims from canonical v2 code.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"io/fs"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

const canonicalImport = "github.com/kubeflow/pipelines/backend/api/v2/"

type declaration struct {
	kind token.Token
	name string
}

type apiPackage struct {
	name           string
	symbols        map[string]declaration
	httpClientType string
}

func legacyName(name string) string {
	name = strings.Replace(name, "V2", "V2beta1", 1)
	return strings.Replace(name, "File_backend_api_v2_", "File_backend_api_v2beta1_", 1)
}

func collectPackages(root string) (map[string]*apiPackage, error) {
	packages := make(map[string]*apiPackage)
	err := filepath.WalkDir(root, func(path string, entry fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if entry.IsDir() || !strings.HasSuffix(path, ".go") || strings.HasSuffix(path, "_test.go") {
			return nil
		}
		file, err := parser.ParseFile(token.NewFileSet(), path, nil, 0)
		if err != nil {
			return err
		}
		dir, err := filepath.Rel(root, filepath.Dir(path))
		if err != nil {
			return err
		}
		pkg := packages[dir]
		if pkg == nil {
			pkg = &apiPackage{name: file.Name.Name, symbols: make(map[string]declaration)}
			packages[dir] = pkg
		}
		if pkg.name != file.Name.Name {
			return fmt.Errorf("mixed package names in %s; keep client tests in an external directory", dir)
		}
		add := func(kind token.Token, name *ast.Ident) error {
			if !name.IsExported() {
				return nil
			}
			legacy := legacyName(name.Name)
			if _, exists := pkg.symbols[legacy]; exists {
				return fmt.Errorf("duplicate compatibility symbol %s in %s; use distinct canonical names", legacy, dir)
			}
			pkg.symbols[legacy] = declaration{kind: kind, name: name.Name}
			return nil
		}
		for _, decl := range file.Decls {
			switch decl := decl.(type) {
			case *ast.FuncDecl:
				if decl.Recv == nil && decl.Name.Name == "NewHTTPClient" {
					if decl.Type.Results == nil || len(decl.Type.Results.List) != 1 {
						return fmt.Errorf("unexpected NewHTTPClient signature in %s; update the compatibility generator", dir)
					}
					pointer, ok := decl.Type.Results.List[0].Type.(*ast.StarExpr)
					if !ok {
						return fmt.Errorf("NewHTTPClient in %s must return a pointer; update the compatibility generator", dir)
					}
					name, ok := pointer.X.(*ast.Ident)
					if !ok {
						return fmt.Errorf("NewHTTPClient in %s must return a local type; update the compatibility generator", dir)
					}
					pkg.httpClientType = name.Name
				}
				if decl.Recv == nil {
					if err := add(token.FUNC, decl.Name); err != nil {
						return err
					}
				}
			case *ast.GenDecl:
				for _, spec := range decl.Specs {
					switch spec := spec.(type) {
					case *ast.TypeSpec:
						if err := add(token.TYPE, spec.Name); err != nil {
							return err
						}
					case *ast.ValueSpec:
						for _, name := range spec.Names {
							if err := add(decl.Tok, name); err != nil {
								return err
							}
						}
					}
				}
			}
		}
		return nil
	})
	return packages, err
}

func renderPackage(pkg *apiPackage, importPath string) ([]byte, error) {
	var output bytes.Buffer
	forwardsHTTPConstructors := pkg.httpClientType != ""
	fmt.Fprintln(&output, "// Code generated by backend/api/hack/generate_compat. DO NOT EDIT.")
	fmt.Fprintln(&output, "// Copyright 2026 The Kubeflow Authors")
	fmt.Fprintln(&output, "// Licensed under the Apache License, Version 2.0.")
	fmt.Fprintf(&output, "\n// Package %s forwards legacy imports to the canonical v2 implementation.\n", pkg.name)
	fmt.Fprintf(&output, "// New code should import %s.\npackage %s\n\n", importPath, pkg.name)
	switch {
	case importPath == canonicalImport+"go_client":
		fmt.Fprintf(&output, "import (\ncanonical %q\n_ %q\n)\n", importPath, "github.com/kubeflow/pipelines/backend/api/v2beta1")
	case forwardsHTTPConstructors:
		fmt.Fprintf(&output, "import (\ncanonical %q\n%q\n)\n", importPath, "github.com/go-openapi/strfmt")
	default:
		fmt.Fprintf(&output, "import canonical %q\n", importPath)
	}
	for _, kind := range []token.Token{token.TYPE, token.CONST, token.VAR} {
		names := make([]string, 0)
		for name, decl := range pkg.symbols {
			if forwardsHTTPConstructors && (name == "NewHTTPClient" || name == "NewHTTPClientWithConfig" || name == "DefaultTransportConfig") {
				continue
			}
			if decl.kind == kind || (kind == token.VAR && decl.kind == token.FUNC) {
				names = append(names, name)
			}
		}
		if len(names) == 0 {
			continue
		}
		sort.Strings(names)
		fmt.Fprintf(&output, "\n%s (\n", kind)
		for _, name := range names {
			fmt.Fprintf(&output, "%s = canonical.%s\n", name, pkg.symbols[name].name)
		}
		fmt.Fprintln(&output, ")")
	}
	if forwardsHTTPConstructors {
		// Package variables cannot be Go aliases. Preserve callers that assign
		// DefaultSchemes while delegating transport creation and methods to v2.
		fmt.Fprintf(&output, `
// DefaultTransportConfig returns canonical defaults with the legacy DefaultSchemes setting.
//
// Deprecated: use the v2 client package.
func DefaultTransportConfig() *TransportConfig {
	config := canonical.DefaultTransportConfig()
	config.Schemes = DefaultSchemes
	return config
}

// NewHTTPClient delegates construction to v2 using legacy transport defaults.
//
// Deprecated: use the v2 client package.
func NewHTTPClient(formats strfmt.Registry) *%s {
	return NewHTTPClientWithConfig(formats, nil)
}

// NewHTTPClientWithConfig delegates construction to v2, preserving legacy nil-config defaults.
//
// Deprecated: use the v2 client package.
func NewHTTPClientWithConfig(formats strfmt.Registry, config *TransportConfig) *%s {
	if config == nil {
		config = DefaultTransportConfig()
	}
	return canonical.NewHTTPClientWithConfig(formats, config)
}
`, pkg.httpClientType, pkg.httpClientType)
	}
	return format.Source(output.Bytes())
}

func generate(root string) error {
	// Render everything before replacing the generated trees. These directories
	// contain only shims; handwritten compatibility code lives one level above.
	outputs := make(map[string][]byte)
	for _, client := range []string{"go_client", "go_http_client"} {
		packages, err := collectPackages(filepath.Join(root, "backend/api/v2", client))
		if err != nil {
			return err
		}
		if len(packages) == 0 {
			return fmt.Errorf("no canonical packages in %s; generate v2 clients first", client)
		}
		for dir, pkg := range packages {
			importPath := canonicalImport + filepath.ToSlash(filepath.Join(client, dir))
			content, err := renderPackage(pkg, importPath)
			if err != nil {
				return err
			}
			outputs[filepath.Join(root, "backend/api/v2beta1", client, dir, "aliases.go")] = content
		}
	}
	for _, client := range []string{"go_client", "go_http_client"} {
		if err := os.RemoveAll(filepath.Join(root, "backend/api/v2beta1", client)); err != nil {
			return err
		}
	}
	for path, content := range outputs {
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(path, content, 0o644); err != nil {
			return err
		}
	}
	return nil
}

func main() {
	root := flag.String("root", ".", "repository root")
	flag.Parse()
	if err := generate(*root); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
