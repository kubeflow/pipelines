"""Generate legacy Python model imports as aliases of canonical v2 models."""

import ast
from pathlib import Path
import sys

HEADER = '# Generated by backend/api/hack/generate_python_compat.py. Do not edit.\n'


def generate(client_root: Path) -> None:
    """Keep top-level and module-qualified v2beta1 imports working."""
    aliases = []
    outputs = {}
    for model in sorted((client_root / 'models').glob('v2_*.py')):
        classes = [
            node.name
            for node in ast.parse(model.read_text()).body
            if isinstance(node, ast.ClassDef) and node.name.startswith('V2')
        ]
        if len(classes) != 1:
            raise ValueError(
                f'Expected one canonical V2 model class in {model}; '
                'regenerate the v2 client and update the compatibility '
                'generator if its class layout has changed')
        canonical = classes[0]
        legacy = canonical.replace('V2', 'V2beta1', 1)
        alias = (f'from kfp.server_api.models.{model.stem} import '
                 f'{canonical} as {legacy}\n')
        outputs[model.with_name(model.name.replace('v2_', 'v2beta1_', 1))] = (
            HEADER + alias)
        aliases.append(alias)
    if not aliases:
        raise ValueError(
            f'No canonical models found in {client_root}; '
            'generate the v2 Python client before compatibility aliases')
    for initializer in (client_root / '__init__.py',
                        client_root / 'models' / '__init__.py'):
        source = initializer.read_text().split(HEADER, 1)[0].rstrip()
        outputs[initializer] = source + '\n\n' + HEADER + ''.join(aliases)
    for path, content in outputs.items():
        path.write_text(content)


if __name__ == '__main__':
    generate(Path(sys.argv[1]))
