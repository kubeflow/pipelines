// Read every old task column so the failed startup cannot silently rewrite a
// source row while reconciling the incompatible target model.
func releasedTaskRows(t *testing.T, db *sql.DB) map[string][]string {
	t.Helper()
	rows, err := db.Query("SELECT `UUID`, `Namespace`, `PipelineName`, `RunUUID`, `PodName`, `MLMDExecutionID`, `CreatedTimestamp`, `StartedTimestamp`, `FinishedTimestamp`, `Fingerprint`, `Name`, `ParentTaskUUID`, `State`, `StateHistory`, `MLMDInputs`, `MLMDOutputs`, `ChildrenPods`, `Payload` FROM `tasks` ORDER BY `UUID`")
	require.NoError(t, err)
	defer rows.Close()
	result := make(map[string][]string)
	for rows.Next() {
		values := make([]sql.RawBytes, 18)
		destinations := make([]any, len(values))
		for i := range values {
			destinations[i] = &values[i]
		}
		require.NoError(t, rows.Scan(destinations...))
		copyValues := make([]string, len(values))
		for i, value := range values {
			if value == nil {
				copyValues[i] = "<SQL NULL>"
			} else {
				copyValues[i] = string(value)
			}
		}
		result[copyValues[0]] = copyValues
	}
	require.NoError(t, rows.Err())
	return result
}

// The database name is generated by the test; only that database is mutated or
// dropped. Test DSNs must point to disposable loopback services, including CI.
func releasedStartupDatabase(t *testing.T, dsn string) (*sql.DB, map[string]any) {
	t.Helper()
	name := "kfp_mlmd_startup_" + strings.ReplaceAll(uuid.NewString(), "-", "")
	settings := map[string]any{"DBDriverName": "mysql", common.DBCredentialProviderEnabled: false}
	config, err := mysqlDriver.ParseDSN(dsn)
	require.NoError(t, err)
	require.Equal(t, "tcp", config.Net)
	require.True(t, config.TLS == nil, "use a disposable MySQL DSN without TLS for the startup reproducer")
	host, port, err := net.SplitHostPort(config.Addr)
	require.NoError(t, err)
	settings[mysqlServiceHost], settings[mysqlServicePort] = host, port
	settings[mysqlUser], settings[mysqlPassword], settings[mysqlDBName] = config.User, config.Passwd, name
	config.DBName = name
	config.MultiStatements = true // The released mysqldump is replayed as one script.
	destination := config.FormatDSN()
	address := net.ParseIP(host)
	require.True(t, host == "localhost" || address != nil && address.IsLoopback(), "use disposable loopback database services")
	root, err := sql.Open("mysql", dsn)
	require.NoError(t, err)
	t.Cleanup(func() { require.NoError(t, root.Close()) })
	_, err = root.Exec("CREATE DATABASE " + name)
	require.NoError(t, err)
	t.Cleanup(func() { _, err := root.Exec("DROP DATABASE " + name); require.NoError(t, err) })
	db, err := sql.Open("mysql", destination)
	require.NoError(t, err)
	t.Cleanup(func() { require.NoError(t, db.Close()) })
	return db, settings
}

func TestMLMDReleasedStartup(t *testing.T) {
	// InitDBClient terminates the process on errors. Use this test binary as an
	// isolated child so the test exercises that real entrypoint without changing it.
	if config := os.Getenv("KFP_MLMD_STARTUP_CHILD_CONFIG"); config != "" {
		var values map[string]any
		require.NoError(t, json.Unmarshal([]byte(config), &values))
		setConfig(t, values)
		db, _, _ := InitDBClient(10 * time.Second)
		require.NoError(t, db.Close())
		return
	}
	dsn := os.Getenv("KFP_MLMD_MYSQL_TEST_DSN")
	if dsn == "" {
		t.Skip("set KFP_MLMD_MYSQL_TEST_DSN to replay the released source in disposable MySQL")
	}
	t.Run("released database", func(t *testing.T) {
		testReleasedStartupFailure(t, dsn, "", "State")
	})
	t.Run("wide legacy task name", func(t *testing.T) {
		testReleasedStartupFailure(t, dsn, strings.Repeat("n", 240), "Name")
	})
}

func testReleasedStartupFailure(t *testing.T, dsn, taskName, failedColumn string) {
	t.Helper()
	db, settings := releasedStartupDatabase(t, dsn)
	dump, err := os.ReadFile("../migration/mlmd/testdata/release_218/source.sql")
	require.NoError(t, err)
	prelude, remainder, found := strings.Cut(string(dump), "CREATE DATABASE /*!32312 IF NOT EXISTS*/ `mlpipeline`")
	require.True(t, found, "the released dump must contain the KFP schema")
	_, source, found := strings.Cut(remainder, "USE `mlpipeline`;")
	require.True(t, found)
	source, _, found = strings.Cut(source, "CREATE DATABASE /*!32312 IF NOT EXISTS*/ `metadb`")
	require.True(t, found, "the released dump must contain the matching MLMD schema")
	_, err = db.Exec(prelude + source)
	require.NoError(t, err, "replay released KFP schema and records")
	const hasNativePods = `SELECT EXISTS(
		SELECT 1 FROM information_schema.COLUMNS
		WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'tasks' AND COLUMN_NAME = 'pods'
	)`
	var nativePods bool
	require.NoError(t, db.QueryRow(hasNativePods).Scan(&nativePods))
	require.False(t, nativePods)
	if taskName != "" {
		_, err := db.Exec("UPDATE tasks SET Name = ? ORDER BY UUID LIMIT 1", taskName)
		require.NoError(t, err)
	}
	before := releasedTaskRows(t, db)
	require.Len(t, before, 191)
	var runCount int
	require.NoError(t, db.QueryRow("SELECT COUNT(*) FROM `run_details`").Scan(&runCount))
	require.Equal(t, 7, runCount)

	config, err := json.Marshal(settings)
	require.NoError(t, err)
	ctx, cancel := context.WithTimeout(context.Background(), 60*time.Second)
	defer cancel()
	cmd := exec.CommandContext(ctx, os.Args[0], "-test.run=^TestMLMDReleasedStartup$", "-test.v")
	cmd.Env = append(os.Environ(), "KFP_MLMD_STARTUP_CHILD_CONFIG="+string(config), "GOTRACEBACK=none")
	output, err := cmd.CombinedOutput()
	require.NoError(t, ctx.Err(), "startup must fail promptly, not time out")
	require.Error(t, err, "current startup must reject the populated released schema")
	require.Contains(t, string(output), "AutoMigrate failed", string(output))
	require.Contains(t, string(output), "column '"+failedColumn+"'", "the failure must be on the old tasks schema")
	require.Equal(t, before, releasedTaskRows(t, db), "failed startup must preserve every released task row")
	require.NoError(t, db.QueryRow(hasNativePods).Scan(&nativePods))
	require.True(t, nativePods, "failed startup leaves partial schema changes")
	for _, line := range strings.Split(string(output), "\n") {
		if strings.Contains(line, "AutoMigrate failed") {
			t.Log(line)
		}
	}
}
