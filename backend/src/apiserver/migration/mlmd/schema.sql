CREATE TABLE `tasks` (
  `UUID` varchar(191) NOT NULL,
  `Namespace` varchar(63) NOT NULL,
  `RunUUID` varchar(191) NOT NULL,
  `pods` json NOT NULL,
  `CreatedAtInSec` bigint NOT NULL,
  `StartedInSec` bigint DEFAULT '0',
  `FinishedInSec` bigint DEFAULT '0',
  `Fingerprint` varchar(255) NOT NULL,
  `Name` varchar(128) DEFAULT NULL,
  `DisplayName` varchar(128) DEFAULT NULL,
  `ParentTaskUUID` varchar(191) DEFAULT NULL,
  `State` int NOT NULL,
  `StatusMetadata` json DEFAULT NULL,
  `StateHistory` json DEFAULT NULL,
  `InputParameters` json DEFAULT NULL,
  `OutputParameters` json DEFAULT NULL,
  `Type` int NOT NULL,
  `TypeAttrs` json NOT NULL,
  `ScopePath` text,
  `LogicalKey` varchar(64) DEFAULT NULL,
  `LifecycleMessage` longtext,
  `LifecycleCategory` varchar(32) DEFAULT NULL,
  PRIMARY KEY (`UUID`),
  UNIQUE KEY `idx_tasks_uuid_run` (`UUID`,`RunUUID`),
  UNIQUE KEY `idx_tasks_logical_key` (`LogicalKey`),
  KEY `idx_task_cache_lookup` (`Fingerprint`,`State`,`Namespace`,`CreatedAtInSec` DESC),
  KEY `idx_parent_run` (`RunUUID`,`ParentTaskUUID`),
  KEY `idx_task_created_timestamp` (`CreatedAtInSec`),
  KEY `idx_task_started_timestamp` (`StartedInSec`),
  KEY `idx_task_finished_timestamp` (`FinishedInSec`),
  KEY `idx_parent_task_uuid` (`ParentTaskUUID`),
  KEY `idx_task_type` (`Type`),
  CONSTRAINT `fk_run_details_tasks` FOREIGN KEY (`RunUUID`) REFERENCES `run_details` (`UUID`),
  CONSTRAINT `fk_tasks_parent_task` FOREIGN KEY (`ParentTaskUUID`) REFERENCES `tasks` (`UUID`) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE `artifacts` (
  `UUID` varchar(191) NOT NULL,
  `Namespace` varchar(63) NOT NULL,
  `Type` int DEFAULT NULL,
  `URI` varchar(2048) DEFAULT NULL,
  `URIHash` varchar(64) DEFAULT NULL,
  `Name` varchar(128) DEFAULT NULL,
  `Description` text,
  `CreatedAtInSec` bigint NOT NULL DEFAULT '0',
  `LastUpdateInSec` bigint NOT NULL DEFAULT '0',
  `Metadata` json DEFAULT NULL,
  `NumberValue` double DEFAULT NULL,
  `IdentityKey` varchar(64) DEFAULT NULL,
  PRIMARY KEY (`UUID`),
  UNIQUE KEY `idx_artifact_identity` (`Namespace`,`IdentityKey`),
  KEY `idx_type_namespace` (`Namespace`,`Type`),
  KEY `idx_namespace_urihash` (`Namespace`,`URIHash`),
  KEY `idx_artifact_created_timestamp` (`CreatedAtInSec`),
  KEY `idx_artifact_last_update_timestamp` (`LastUpdateInSec`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE `artifact_tasks` (
  `UUID` varchar(191) NOT NULL,
  `ArtifactID` varchar(191) NOT NULL,
  `TaskID` varchar(191) NOT NULL,
  `Type` int NOT NULL,
  `Iteration` bigint NOT NULL DEFAULT '-1',
  `RunUUID` varchar(191) NOT NULL,
  `Producer` json DEFAULT NULL,
  `ArtifactKey` varchar(191) NOT NULL DEFAULT '',
  PRIMARY KEY (`UUID`),
  UNIQUE KEY `UniqueLink` (`ArtifactID`,`TaskID`,`Type`,`Iteration`,`ArtifactKey`),
  KEY `idx_link_artifact_id` (`ArtifactID`),
  KEY `idx_link_task_run` (`TaskID`,`RunUUID`),
  KEY `idx_link_run_id` (`RunUUID`),
  CONSTRAINT `fk_artifact_tasks_artifacts` FOREIGN KEY (`ArtifactID`) REFERENCES `artifacts` (`UUID`) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT `fk_artifact_tasks_runs` FOREIGN KEY (`RunUUID`) REFERENCES `run_details` (`UUID`) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT `fk_artifact_tasks_task_run` FOREIGN KEY (`TaskID`, `RunUUID`) REFERENCES `tasks` (`UUID`, `RunUUID`) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
